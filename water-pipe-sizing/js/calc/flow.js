/*
 * 器具給水負荷単位 → 同時使用流量
 * SHASE-S 206 の同時使用流量線図（Hunter 曲線系）を数表化した近似値。
 *  曲線① valve : 大便器洗浄弁が多い場合
 *  曲線② tank  : 大便器洗浄タンクが多い場合
 * 元データは gpm（Hunter 表）で、L/min に換算して用いる。表間は線形補間、範囲外は端部の勾配で外挿。
 */
(function (WPS) {
  'use strict';

  const GPM_TO_LPM = 3.785411784;

  const TANK_GPM = [
    [1, 3.0], [2, 5.0], [3, 6.5], [4, 8.0], [5, 9.4], [6, 10.7], [7, 11.8], [8, 12.8], [9, 13.7],
    [10, 14.6], [11, 15.4], [12, 16.0], [13, 16.5], [14, 17.0], [15, 17.5], [16, 18.0], [17, 18.4],
    [18, 18.8], [19, 19.2], [20, 19.6], [25, 21.5], [30, 23.3], [35, 24.9], [40, 26.3], [45, 27.7],
    [50, 29.1], [60, 32.0], [70, 35.0], [80, 38.0], [90, 41.0], [100, 43.5], [120, 48.0], [140, 52.5],
    [160, 57.0], [180, 61.0], [200, 65.0], [225, 70.0], [250, 75.0], [275, 80.0], [300, 85.0],
    [400, 105.0], [500, 124.0], [750, 170.0], [1000, 208.0], [1250, 239.0], [1500, 269.0],
    [1750, 297.0], [2000, 325.0], [2500, 380.0], [3000, 433.0], [4000, 525.0], [5000, 593.0],
  ];

  const VALVE_GPM = [
    [5, 15.0], [6, 17.4], [7, 19.8], [8, 22.2], [9, 24.6], [10, 27.0], [11, 27.8], [12, 28.6],
    [13, 29.4], [14, 30.2], [15, 31.0], [16, 31.8], [17, 32.6], [18, 33.4], [19, 34.2], [20, 35.0],
    [25, 38.0], [30, 42.0], [35, 44.0], [40, 46.0], [45, 48.0], [50, 50.0], [60, 54.0], [70, 58.0],
    [80, 61.2], [90, 64.3], [100, 67.5], [120, 73.0], [140, 77.0], [160, 81.0], [180, 85.5],
    [200, 90.0], [225, 95.5], [250, 101.0], [275, 104.5], [300, 108.0], [400, 127.0], [500, 143.0],
    [750, 177.0], [1000, 208.0], [1250, 239.0], [1500, 269.0], [1750, 297.0], [2000, 325.0],
    [2500, 380.0], [3000, 433.0], [4000, 525.0], [5000, 593.0],
  ];

  const toLpm = (t) => t.map(([fu, g]) => [fu, g * GPM_TO_LPM]);
  const CURVES = { tank: toLpm(TANK_GPM), valve: toLpm(VALVE_GPM) };

  function interp(table, x) {
    if (!(x > 0)) return 0;
    const first = table[0];
    if (x <= first[0]) return first[1] * (x / first[0]);
    for (let i = 1; i < table.length; i++) {
      const [x1, y1] = table[i];
      if (x <= x1) {
        const [x0, y0] = table[i - 1];
        return y0 + (y1 - y0) * (x - x0) / (x1 - x0);
      }
    }
    const [xa, ya] = table[table.length - 2];
    const [xb, yb] = table[table.length - 1];
    return yb + (yb - ya) * (x - xb) / (xb - xa);
  }

  WPS.flow = {
    CURVES,
    CURVE_LABEL: { valve: '①洗浄弁', tank: '②洗浄タンク' },
    /* 負荷単位 fu → 同時使用流量 [L/min] */
    fuToFlow(fu, curve) {
      return interp(CURVES[curve === 'valve' ? 'valve' : 'tank'], fu);
    },
  };
})(globalThis.WPS = globalThis.WPS || {});
